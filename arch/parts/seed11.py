"""第十一批：线下现场（仓库、门店、游乐场、旅社）。

为什么补这一域：

  前面所有域都在回答「屏幕里那个软件怎么装」。但有四类生意，软件只是它身上的一层皮，
  真正的约束在**物理世界**：

  · 仓库：货在货架上，人在动线上走。系统说「有货」而货架上是空的，生意当场就停。
  · 咖啡厅 / 门店：早高峰八分钟出四十杯。点单软件卡一下，队伍就排到门外。
  · 游乐场：闸机、手环、设备点检。一次逃票是小事，一次设备伤人不是。
  · 山野旅社：山里没信号、夜里没人值守。断网那一刻，房态和门锁必须还能用。

  这四类活儿的共同解不是「更多功能」，是**离线可用 + 实物对得上 + 有时段**。
  所以这一域切的不是行业，是三条硬约束：

  site.space / in / stock / pick / count   仓：库位、收货、批次、拣货、盘点
  site.order / recipe / channel / shift    店：点单、配方、外卖、班结
  site.ticket / gate / safety              场：票务、闸机、点检
  site.room / lock / duty                  宿：房态、门锁、值守
  site.offgrid                             共用：断网继续营业，回网补单

  与 wms / cafe 的边界：那两个讲的是「后台系统里怎么记账」；site 讲的是
  「柜台前站着人、货架上有货、闸机要开」的时候，这套东西还转不转。
"""
