"""第八批：把「个人中台」扩成「任何一台要长期用的东西」，并补上模块之间的缝。

为什么要补：第七批只回答了「一个常驻桌面的软件」的七件事。但用户真正要做的东西是
「仓库管理」「跨境电商」「无人机操纵台」「放置游戏」「生图开发台」「移动热点」——
它们和桌面中台共用的只是「数据 + 界面 + 外壳」，剩下全是各自的：库存怎么扣、
订单怎么拆、支付怎么对账、地图坐标怎么转、游戏主循环怎么跑、设备怎么配网。

切法还是同一把尺子：**只切「必须自己决定、选错了要返工」的**。
  库存   用「先查后扣」＝大促必然超卖，必须用条件更新或行锁
  订单   状态机不先定死＝退款、拆包、部分发货各写一套，最后对不上
  支付   不存幂等键＝用户点两次就扣两次钱
  坐标   不统一坐标系＝无人机轨迹在地图上偏 500 米
  主循环 用 setInterval 驱逻辑＝切后台就掉帧、离线收益算错
  配网   不做失败回退＝用户第一次连不上就退货

这批还补了四类「缝」（用户叫它代码胶水）：事件总线、后台任务、进程通信、数据契约、
备份迁移、自动化触发、分享协作。它们不属于任何单个功能，但**每个新模块加进来都要从
这里穿过去**——先有缝，后加模块才不用改已装好的部分。

新增四个域：
  biz   交易与库存（商品、库存、订单、支付、物流、会员）
  game  游戏运行（主循环、存档、数值、商店）
  map   位置与地图（底图、定位、轨迹）
  ops   运行与运维（部署、监控、告警）
"""
